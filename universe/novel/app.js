let locale = "zh";
const followKey = "echo.novel.following";
const progressKey = "echo.novel.stranger-memory.progress";
const governanceEndpoint = "/api/canon/candidates/stranger-memory/governance";
let governanceState = null;
let governanceBusy = false;

function preferredLocale() {
  const query = new URLSearchParams(location.search).get("lang");
  if (query === "zh" || query === "en") return query;
  try { const saved = localStorage.getItem("echo.locale"); if (saved === "zh" || saved === "en") return saved; } catch (_) {}
  return navigator.language.toLowerCase().startsWith("zh") ? "zh" : "en";
}

function following() { try { return localStorage.getItem(followKey) === "true"; } catch (_) { return false; } }

function syncFollow() {
  const active = following();
  const button = document.querySelector("#follow-button");
  button?.setAttribute("aria-pressed", String(active));
  if (button) { button.classList.toggle("active", active); button.querySelector("span").textContent = novelCopy[locale][active ? "followingWork" : "followWork"]; button.querySelector("i").textContent = active ? "✓" : "＋"; }
}

function showToast(message) {
  const toast = document.querySelector("#novel-toast");
  if (!toast) return;
  toast.textContent = message; toast.classList.add("show");
  clearTimeout(showToast.timer); showToast.timer = setTimeout(() => toast.classList.remove("show"), 1800);
}

function governanceHeaders() {
  try {
    const token = localStorage.getItem("echo.auth.token");
    return token ? { Authorization: `Bearer ${token}` } : {};
  } catch (_) {
    return {};
  }
}

function setGovernanceText(selector, value) {
  const target = document.querySelector(selector);
  if (target) target.textContent = value;
}

function renderGovernance() {
  const protocol = document.querySelector("#governance-protocol");
  if (!protocol || !governanceState) return;
  const copy = novelCopy[locale];
  const resonance = governanceState.resonance;
  const continuity = governanceState.continuity;
  const committee = governanceState.committee;
  const gate = governanceState.promotion_gate;
  const formatter = new Intl.NumberFormat(locale === "zh" ? "zh-CN" : "en");

  protocol.dataset.state = gate.state;
  document.querySelector("#governance-error")?.setAttribute("hidden", "");
  setGovernanceText("#resonance-total", formatter.format(resonance.total));
  setGovernanceText("#resonance-support-count", formatter.format(resonance.support));
  setGovernanceText("#resonance-revise-count", formatter.format(resonance.revise));
  setGovernanceText("#registered-resonance-count", formatter.format(resonance.registered.total));
  setGovernanceText("#anonymous-resonance-count", formatter.format(resonance.anonymous.total));
  setGovernanceText("#resonance-step-status", copy[resonance.open ? "resonanceOpen" : "resonanceClosed"]);
  setGovernanceText(
    "#continuity-step-status",
    copy[continuity.status === "passed" ? "continuityPassed" : continuity.status === "vetoed" ? "continuityVetoed" : "continuityPending"],
  );
  setGovernanceText("#committee-step-status", `${committee.approvals} / ${committee.size} · ≥${committee.threshold}`);
  const promotionKey = governanceState.promotion.promoted
    ? "promotionDone"
    : gate.state === "ready"
      ? "promotionReady"
      : gate.state === "blocked"
        ? "promotionBlocked"
        : "promotionLocked";
  setGovernanceText("#promotion-step-status", copy[promotionKey]);

  const percent = resonance.total ? Math.round(resonance.support_ratio * 100) : 0;
  const meter = document.querySelector("#resonance-meter-fill");
  if (meter) meter.style.width = `${percent}%`;
  document.querySelector(".resonance-meter")?.setAttribute("aria-label", `${copy.resonanceRatio}: ${percent}%`);
  document.querySelectorAll("[data-resonance-choice]").forEach((button) => {
    const active = resonance.viewer_choice === button.dataset.resonanceChoice;
    button.classList.toggle("active", active);
    button.setAttribute("aria-pressed", String(active));
    button.disabled = governanceBusy || !resonance.open;
  });

  document.querySelector("#continuity-step-status")?.classList.toggle("done", continuity.status === "passed");
  document.querySelector("#continuity-step-status")?.classList.toggle("blocked", continuity.status === "vetoed");
  document.querySelector("#committee-step-status")?.classList.toggle("done", committee.approvals >= committee.threshold);
  document.querySelector("#promotion-step-status")?.classList.toggle("done", gate.state === "ready" || governanceState.promotion.promoted);
  document.querySelector("#promotion-step-status")?.classList.toggle("blocked", gate.state === "blocked");
}

function renderGovernanceUnavailable() {
  const protocol = document.querySelector("#governance-protocol");
  if (protocol) protocol.dataset.state = "unavailable";
  const error = document.querySelector("#governance-error");
  if (error) error.hidden = false;
  document.querySelectorAll("[data-resonance-choice]").forEach((button) => { button.disabled = true; });
}

async function loadGovernance() {
  try {
    const response = await fetch(governanceEndpoint, {
      credentials: "same-origin",
      headers: governanceHeaders(),
      cache: "no-store",
    });
    if (!response.ok) throw new Error(String(response.status));
    governanceState = await response.json();
    renderGovernance();
  } catch (_) {
    renderGovernanceUnavailable();
  }
}

async function updateResonance(choice) {
  if (!governanceState || governanceBusy) return;
  const nextChoice = governanceState.resonance.viewer_choice === choice ? null : choice;
  governanceBusy = true;
  renderGovernance();
  try {
    const response = await fetch("/api/canon/candidates/stranger-memory/resonance", {
      method: "PUT",
      credentials: "same-origin",
      headers: { "Content-Type": "application/json", ...governanceHeaders() },
      body: JSON.stringify({ choice: nextChoice }),
    });
    if (!response.ok) throw new Error(String(response.status));
    governanceState = await response.json();
    showToast(novelCopy[locale][nextChoice ? "resonanceSaved" : "resonanceWithdrawn"]);
  } catch (_) {
    showToast(novelCopy[locale].resonanceFailed);
  } finally {
    governanceBusy = false;
    renderGovernance();
  }
}

function applyLocale(next, updateUrl = true) {
  locale = next === "en" ? "en" : "zh";
  const copy = novelCopy[locale];
  document.documentElement.lang = locale === "en" ? "en" : "zh-CN";
  document.querySelectorAll("[data-i18n]").forEach((element) => { if (copy[element.dataset.i18n] !== undefined) element.textContent = copy[element.dataset.i18n]; });
  document.querySelectorAll("[data-i18n-aria]").forEach((element) => { if (copy[element.dataset.i18nAria] !== undefined) element.setAttribute("aria-label", copy[element.dataset.i18nAria]); });
  document.querySelectorAll("[data-locale]").forEach((button) => { const active = button.dataset.locale === locale; button.classList.toggle("active", active); button.setAttribute("aria-pressed", String(active)); });
  document.title = copy.pageTitle;
  document.querySelector('meta[name="description"]')?.setAttribute("content", copy.pageDescription);
  document.querySelector('meta[property="og:title"]')?.setAttribute("content", copy.pageTitle);
  document.querySelector('meta[property="og:description"]')?.setAttribute("content", copy.pageDescription);
  document.querySelector('meta[property="og:locale"]')?.setAttribute("content", locale === "en" ? "en_US" : "zh_CN");
  document.querySelectorAll("[data-reader-link]").forEach((link) => { const url = new URL(link.href); url.searchParams.set("lang", locale); link.href = `${url.pathname}${url.search}`; });
  try { localStorage.setItem("echo.locale", locale); } catch (_) {}
  if (updateUrl) { const url = new URL(location.href); url.searchParams.set("lang", locale); history.replaceState({}, "", url); }
  const primaryLabel = document.querySelector(".novel-hero-actions .primary-action span");
  if (primaryLabel && savedProgress > 2) primaryLabel.textContent = `${copy.continueReading} ${Math.round(savedProgress)}%`;
  syncFollow();
  renderGovernance();
}

document.querySelectorAll("[data-locale]").forEach((button) => button.addEventListener("click", () => applyLocale(button.dataset.locale)));
document.querySelector("#follow-button")?.addEventListener("click", () => { const value = !following(); try { localStorage.setItem(followKey, String(value)); } catch (_) {} syncFollow(); showToast(novelCopy[locale][value ? "followedToast" : "unfollowedToast"]); });
document.querySelectorAll("[data-resonance-choice]").forEach((button) => button.addEventListener("click", () => updateResonance(button.dataset.resonanceChoice)));

let savedProgress = 0;
try { savedProgress = Math.max(0, Math.min(100, Number(localStorage.getItem(progressKey)) || 0)); } catch (_) {}
document.querySelector("#saved-progress").textContent = `${Math.round(savedProgress)}%`;

const header = document.querySelector(".universe-header");
window.addEventListener("scroll", () => header?.classList.toggle("scrolled", scrollY > 20), { passive: true });
applyLocale(preferredLocale(), false);
loadGovernance();
window.setInterval(() => {
  if (!document.hidden && !governanceBusy) loadGovernance();
}, 30_000);
