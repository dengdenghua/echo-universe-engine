function drawMemoryTerrain(width, box, random) {
  const startX = width * .31;
  const baseline = box.top + box.height * .75;
  const span = width - startX;
  context.save();
  context.globalCompositeOperation = "lighter";

  for (let layer = 0; layer < 14; layer += 1) {
    context.beginPath();
    for (let x = startX; x <= width + 3; x += 4) {
      const t = (x - startX) / span;
      const ridge = -Math.sin(t * Math.PI) * box.height * (.16 + layer * .0015) + Math.sin(t * Math.PI * 4.8 + layer * .13) * box.height * .035 + Math.sin(t * Math.PI * 9.2) * box.height * .012;
      const y = baseline + ridge + layer * 1.7;
      if (x === startX) context.moveTo(x, y); else context.lineTo(x, y);
    }
    context.strokeStyle = layer % 4 === 0 ? "rgba(178,117,255,.31)" : "rgba(99,146,255,.27)";
    context.lineWidth = .62;
    context.stroke();
  }

  for (let index = 0; index < 1350; index += 1) {
    const x = startX + random() * span;
    const t = (x - startX) / span;
    const ridge = -Math.sin(t * Math.PI) * box.height * .16 + Math.sin(t * Math.PI * 4.8 + random() * .35) * box.height * .035;
    const fillDepth = random() > .38 ? random() * box.height * .19 : (random() - .5) * box.height * .08;
    const y = baseline + ridge + fillDepth;
    point(x, y, .22 + random() * .62, random() > .82 ? "#bf8dff" : "#91b4ff", .22 + random() * .58);
  }

  for (let column = 0; column < 64; column += 1) {
    const x = startX + (column / 63) * span;
    const t = column / 63;
    const ridge = baseline - Math.sin(t * Math.PI) * box.height * .16 + Math.sin(t * Math.PI * 4.8) * box.height * .035;
    const height = Math.max(box.height * .04, baseline - ridge + box.height * (.03 + random() * .13));
    const gradient = context.createLinearGradient(x, ridge - height * .12, x, baseline + box.height * .08);
    gradient.addColorStop(0, "rgba(113,150,255,0)");
    gradient.addColorStop(1, "rgba(113,150,255,.18)");
    context.strokeStyle = gradient;
    context.lineWidth = .55;
    context.beginPath();
    context.moveTo(x, ridge - height * .12);
    context.lineTo(x, baseline + box.height * .08);
    context.stroke();
  }
  context.restore();
}

