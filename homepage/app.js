function drawFinalHorizon(width, box, random) {
  const centerX = width * .39;
  const centerY = box.top + box.height * .94;
  const radiusX = width * .61;
  const radiusY = box.height * .5;
  context.save();
  context.globalCompositeOperation = "lighter";

  for (let layer = 0; layer < 10; layer += 1) {
    context.beginPath();
    const rx = radiusX * (1 - layer * .025);
    const ry = radiusY * (1 - layer * .06);
    for (let step = 0; step <= 160; step += 1) {
      const angle = Math.PI + (step / 160) * Math.PI;
      const x = centerX + Math.cos(angle) * rx;
      const y = centerY + Math.sin(angle) * ry;
      if (step === 0) context.moveTo(x, y); else context.lineTo(x, y);
    }
    context.strokeStyle = layer % 3 === 0 ? "rgba(178,112,255,.35)" : "rgba(89,142,255,.37)";
    context.lineWidth = layer === 0 ? .95 : .58;
    context.stroke();
  }

  for (let index = 0; index < 900; index += 1) {
    const angle = Math.PI + random() * Math.PI;
    const depth = .72 + random() * .3;
    const x = centerX + Math.cos(angle) * radiusX * depth;
    const y = centerY + Math.sin(angle) * radiusY * depth + (random() - .5) * 4;
    point(x, y, .24 + random() * .65, random() > .83 ? "#c48fff" : "#8ab1ff", .25 + random() * .58);
  }

  const sunriseY = centerY - radiusY;
  const sunrise = context.createRadialGradient(centerX, sunriseY, 0, centerX, sunriseY, box.height * .18);
  sunrise.addColorStop(0, "rgba(255,221,176,.95)");
  sunrise.addColorStop(.06, "rgba(255,139,77,.65)");
  sunrise.addColorStop(.28, "rgba(181,83,146,.22)");
  sunrise.addColorStop(1, "rgba(52,70,170,0)");
  context.fillStyle = sunrise;
  context.fillRect(centerX - box.height * .2, sunriseY - box.height * .2, box.height * .4, box.height * .4);
  context.restore();
}

function renderCosmos() {
  renderFrame = 0;
  const width = main.clientWidth;
  const height = main.scrollHeight;
  if (!width || !height) return;
  const pixelBudget = width <= 900 ? 5_000_000 : 8_000_000;
  const budgetRatio = Math.sqrt(pixelBudget / (width * height));
  const ratio = Math.max(.75, Math.min(window.devicePixelRatio || 1, 1.75, budgetRatio));
  canvas.width = Math.floor(width * ratio);
  canvas.height = Math.floor(height * ratio);
  canvas.style.width = `${width}px`;
  canvas.style.height = `${height}px`;
  context.setTransform(ratio, 0, 0, ratio, 0, 0);
  context.clearRect(0, 0, width, height);

  const random = seededRandom(20260824 + Math.round(width));
  drawStars(width, height, random);
  drawHeroParticles(width, sectionMetrics(".hero"), random);
  drawMemoryTerrain(width, sectionMetrics(".memory-section"), random);
  drawFieldDust(width, sectionMetrics(".memory-field"), random);
  drawFinalHorizon(width, sectionMetrics(".final-section"), random);
  context.globalAlpha = 1;
  context.globalCompositeOperation = "source-over";
}

function scheduleCosmosRender() {
  if (renderFrame) cancelAnimationFrame(renderFrame);
  renderFrame = requestAnimationFrame(renderCosmos);
}

