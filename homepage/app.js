function resolveInitialLocale() {
  const requested = new URLSearchParams(location.search).get("lang")?.toLowerCase();
  if (requested?.startsWith("zh")) return "zh";
  if (requested === "en") return "en";
  try {
    const saved = localStorage.getItem("echo.locale");
    if (saved === "zh" || saved === "en") return saved;
  } catch (_) {
    // The active page can still use the browser language when storage is unavailable.
  }
  return navigator.language.toLowerCase().startsWith("zh") ? "zh" : "en";
}

function applyLocale(locale, updateUrl = true) {
  const selected = locale === "en" ? "en" : "zh";
  const copy = translations[selected];
  const metadata = localeMetadata[selected];

  document.documentElement.lang = metadata.lang;
  document.documentElement.dataset.locale = selected;
  document.title = metadata.title;
  document.querySelector('meta[name="description"]')?.setAttribute("content", metadata.description);
  document.querySelector('meta[property="og:title"]')?.setAttribute("content", metadata.title);
  document.querySelector('meta[property="og:description"]')?.setAttribute("content", metadata.socialDescription);

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const value = copy[element.dataset.i18n];
    if (value !== undefined) element.textContent = value;
  });
  document.querySelectorAll("[data-i18n-html]").forEach((element) => {
    const value = copy[element.dataset.i18nHtml];
    if (value !== undefined) element.innerHTML = value;
  });
  document.querySelectorAll("[data-i18n-aria]").forEach((element) => {
    const value = copy[element.dataset.i18nAria];
    if (value !== undefined) element.setAttribute("aria-label", value);
  });
  document.querySelectorAll("[data-locale]").forEach((button) => {
    const active = button.dataset.locale === selected;
    button.classList.toggle("active", active);
    button.setAttribute("aria-pressed", String(active));
  });

  try {
    localStorage.setItem("echo.locale", selected);
  } catch (_) {
    // Locale selection remains active for this page.
  }
  if (updateUrl) {
    const url = new URL(location.href);
    url.searchParams.set("lang", selected);
    history.replaceState({ locale: selected }, "", url);
  }
  document.querySelectorAll('a[href^="/universe/"]').forEach((link) => {
    const target = new URL(link.href);
    target.searchParams.set("lang", selected);
    link.href = target.pathname + target.search + target.hash;
  });
}

document.querySelectorAll("[data-locale]").forEach((button) => {
  button.addEventListener("click", () => applyLocale(button.dataset.locale));
});

const siteHeader = document.querySelector(".site-header");
const navigationItems = Array.from(document.querySelectorAll('.main-nav a[href^="#"]'))
  .map((link) => ({ link, section: document.querySelector(link.getAttribute("href")) }))
  .filter((item) => item.section);
let pageChromeFrame = 0;

function syncPageChrome() {
  pageChromeFrame = 0;
  siteHeader?.classList.toggle("is-scrolled", window.scrollY > 20);

  const focusLine = window.scrollY + window.innerHeight * .36;
  let currentItem = null;
  navigationItems.forEach((item) => {
    if (item.section.offsetTop <= focusLine) currentItem = item;
  });
  navigationItems.forEach((item) => {
    const active = item === currentItem;
    item.link.classList.toggle("active", active);
    if (active) item.link.setAttribute("aria-current", "location");
    else item.link.removeAttribute("aria-current");
  });
}

function schedulePageChromeSync() {
  if (pageChromeFrame) return;
  pageChromeFrame = requestAnimationFrame(syncPageChrome);
}

window.addEventListener("scroll", schedulePageChromeSync, { passive: true });
window.addEventListener("resize", schedulePageChromeSync, { passive: true });
window.addEventListener("hashchange", schedulePageChromeSync);
syncPageChrome();

