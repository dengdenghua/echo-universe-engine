function prepareMotionCanvas(motionCanvas, motionContext) {
  const width = Math.max(1, Math.round(motionCanvas.clientWidth));
  const height = Math.max(1, Math.round(motionCanvas.clientHeight));
  const ratio = Math.max(1, Math.min(window.devicePixelRatio || 1, 1.5, Math.sqrt(2_500_000 / (width * height))));
  const pixelWidth = Math.round(width * ratio);
  const pixelHeight = Math.round(height * ratio);
  if (motionCanvas.width !== pixelWidth || motionCanvas.height !== pixelHeight) {
    motionCanvas.width = pixelWidth;
    motionCanvas.height = pixelHeight;
    motionCanvas.style.width = `${width}px`;
    motionCanvas.style.height = `${height}px`;
  }
  motionContext.setTransform(ratio, 0, 0, ratio, 0, 0);
  motionContext.clearRect(0, 0, width, height);
  return { width, height };
}

function motionPoint(motionContext, x, y, radius, color, alpha) {
  motionContext.globalAlpha = alpha;
  motionContext.fillStyle = color;
  motionContext.beginPath();
  motionContext.arc(x, y, radius, 0, Math.PI * 2);
  motionContext.fill();
}

function drawHeroMotion(time) {
  const { width, height } = prepareMotionCanvas(heroMotionCanvas, heroMotionContext);
  const geometry = heroEchoGeometry(width, height);
  const { centerX, centerY, radius, startAngle, endAngle, compact } = geometry;
  const arcSpan = endAngle - startAngle;
  const signalX = centerX + radius * (compact ? 1.02 : 1.18);
  const breath = .5 + Math.sin(time * .00105) * .5;
  heroMotionContext.save();
  heroMotionContext.globalCompositeOperation = "lighter";

  const ringGradient = heroMotionContext.createLinearGradient(
    centerX - radius,
    centerY - radius,
    centerX + radius,
    centerY + radius,
  );
  ringGradient.addColorStop(0, "rgba(230,242,255,.78)");
  ringGradient.addColorStop(.4, "rgba(141,190,255,.7)");
  ringGradient.addColorStop(.74, "rgba(106,143,255,.56)");
  ringGradient.addColorStop(1, "rgba(235,246,255,.82)");

  heroMotionContext.shadowColor = "rgba(91,151,255,.56)";
  heroMotionContext.shadowBlur = compact ? 16 : 24;
  strokeEchoArc(heroMotionContext, geometry, radius, ringGradient, Math.max(6, radius * .025), .055 + breath * .045);
  heroMotionContext.shadowBlur = 0;
  strokeEchoArc(heroMotionContext, geometry, radius, ringGradient, 1.3, .32 + breath * .16);
  strokeEchoArc(heroMotionContext, geometry, radius * .982, "rgba(213,232,255,.82)", .48, .36 + breath * .15);

  for (let wave = 0; wave < 3; wave += 1) {
    const progress = (time * .00017 + wave / 3) % 1;
    const arrival = Math.min(1, progress / .075);
    const fade = arrival * Math.pow(1 - progress, 1.85);
    const waveRadius = radius * (1.045 + progress * (compact ? .62 : .82));
    strokeEchoArc(
      heroMotionContext,
      geometry,
      waveRadius,
      wave === 1 ? "rgba(168,127,255,.7)" : "rgba(114,174,255,.76)",
      .45 + (1 - progress) * .38,
      fade * .15,
      progress * .07,
    );
  }

  const tickCount = compact ? 30 : 48;
  for (let index = 0; index < tickCount; index += 1) {
    const angle = startAngle + ((index + .5) / tickCount) * arcSpan;
    const activity = Math.pow(.5 + Math.sin(time * .0013 + index * 1.73) * .5, 5);
    const inner = radius * 1.035;
    const length = 2.5 + activity * (index % 8 === 0 ? 8 : 3.5);
    heroMotionContext.globalAlpha = .08 + activity * .34;
    heroMotionContext.strokeStyle = index % 11 === 0 ? "#d0b0ff" : "#a9d1ff";
    heroMotionContext.lineWidth = index % 8 === 0 ? .65 : .38;
    heroMotionContext.beginPath();
    heroMotionContext.moveTo(centerX + Math.cos(angle) * inner, centerY + Math.sin(angle) * inner);
    heroMotionContext.lineTo(centerX + Math.cos(angle) * (inner + length), centerY + Math.sin(angle) * (inner + length));
    heroMotionContext.stroke();
  }

  [startAngle, endAngle].forEach((angle, index) => {
    const terminalX = centerX + Math.cos(angle) * radius;
    const terminalY = centerY + Math.sin(angle) * radius;
    const terminalPulse = .66 + Math.sin(time * .0018 + index * Math.PI) * .3;
    motionPoint(heroMotionContext, terminalX, terminalY, compact ? 1.55 : 2, "#e5f3ff", terminalPulse);
  });

  /* 窄屏只画前 300 个火花。这是每帧成本最高的一段（720 个点各带 sin 运算与
     可选拖尾），而手机上环半径本来就小，多出的点会挤在一起看不出差别。
     取前缀而不是按 compact 重新生成数组：火花参数出自同一条 seeded 序列，
     截断前缀在两种视口下形状一致，缩放窗口时不会整片重排。 */
  const sparkBudget = compact ? 300 : heroSparks.length;
  for (let sparkIndex = 0; sparkIndex < sparkBudget; sparkIndex += 1) {
    const spark = heroSparks[sparkIndex];
    const echoProgress = (spark.echoOffset + time * .00017) % 1;
    const waveLift = spark.ringBound ? 0 : Math.sin(echoProgress * Math.PI) * .035;
    const orbitRadius = radius * (
      spark.shell
      + Math.sin(time * spark.frequency + spark.phase) * spark.radialDrift
      + waveLift
    );
    const angle = spark.angle + Math.sin(time * spark.frequency * .63 + spark.phase) * spark.angularDrift;
    const x = centerX + Math.cos(angle) * orbitRadius;
    const y = centerY + Math.sin(angle) * orbitRadius;
    const pulse = .56 + Math.sin(time * .00092 + spark.phase) * .28;
    const waveResponse = spark.ringBound ? 1 : .62 + Math.sin(echoProgress * Math.PI) * .38;
    if (spark.trail) {
      const tail = 4 + spark.size * 5;
      heroMotionContext.globalAlpha = spark.alpha * pulse * waveResponse * .54;
      heroMotionContext.strokeStyle = spark.violet ? "#c492ff" : "#b2ccff";
      heroMotionContext.lineWidth = .65;
      heroMotionContext.beginPath();
      heroMotionContext.moveTo(x - Math.cos(angle) * tail, y - Math.sin(angle) * tail);
      heroMotionContext.lineTo(x, y);
      heroMotionContext.stroke();
    }
    motionPoint(
      heroMotionContext,
      x,
      y,
      spark.size,
      spark.violet ? "#c9a4ff" : "#acd2ff",
      spark.alpha * pulse * waveResponse,
    );
  }

  heroSignalMotes.forEach((mote) => {
    const progress = (mote.offset + time * mote.speed) % 1;
    const distance = radius * (.045 + progress * .84);
    const x = signalX + distance;
    const y = centerY + Math.sin(progress * Math.PI * 3 + mote.phase) * radius * .012 + mote.lane * radius * progress;
    const alpha = Math.sin(progress * Math.PI) * (1 - progress * .42);
    motionPoint(heroMotionContext, x, y, mote.size, mote.violet ? "#c9a7ff" : "#a7d5ff", Math.max(0, alpha) * .48);
  });

  for (let pulse = 0; pulse < 2; pulse += 1) {
    const progress = (time * .00034 + pulse * .5) % 1;
    heroMotionContext.globalAlpha = Math.pow(1 - progress, 2) * .28;
    heroMotionContext.strokeStyle = pulse ? "#b394ff" : "#9dcbff";
    heroMotionContext.lineWidth = .55;
    heroMotionContext.beginPath();
    heroMotionContext.arc(signalX, centerY, radius * (.035 + progress * .18), 0, fullCircle);
    heroMotionContext.stroke();
  }

  const signalPulse = .72 + Math.sin(time * .0022) * .28;
  const signalGlow = heroMotionContext.createRadialGradient(signalX, centerY, 0, signalX, centerY, radius * .12);
  signalGlow.addColorStop(0, `rgba(245,251,255,${.86 * signalPulse})`);
  signalGlow.addColorStop(.1, `rgba(160,213,255,${.48 * signalPulse})`);
  signalGlow.addColorStop(.4, `rgba(84,136,255,${.14 * signalPulse})`);
  signalGlow.addColorStop(1, "rgba(54,84,219,0)");
  heroMotionContext.globalAlpha = 1;
  heroMotionContext.fillStyle = signalGlow;
  heroMotionContext.fillRect(signalX - radius * .12, centerY - radius * .12, radius * .24, radius * .24);
  motionPoint(heroMotionContext, signalX, centerY, compact ? 2.35 : 3, "#f1f8ff", .8 + signalPulse * .2);
  heroMotionContext.restore();
}

function drawMemoryMotion(time) {
  const { width, height } = prepareMotionCanvas(memoryMotionCanvas, memoryMotionContext);
  const baseline = height * .75;
  memoryMotionContext.save();
  memoryMotionContext.globalCompositeOperation = "lighter";

  for (let wave = 0; wave < 2; wave += 1) {
    memoryMotionContext.beginPath();
    for (let x = 0; x <= width; x += 5) {
      const progress = x / width;
      const y = baseline - Math.sin(progress * Math.PI) * height * .16 + Math.sin(progress * Math.PI * 4.8 + time * .00017 + wave * 1.7) * height * .03 + wave * 3;
      if (x === 0) memoryMotionContext.moveTo(x, y); else memoryMotionContext.lineTo(x, y);
    }
    memoryMotionContext.strokeStyle = wave ? "rgba(182,119,255,.2)" : "rgba(112,153,255,.24)";
    memoryMotionContext.lineWidth = .55;
    memoryMotionContext.stroke();
  }

  memorySparks.forEach((spark) => {
    const progress = (spark.offset + time * spark.speed) % 1;
    const x = progress * width;
    const y = baseline - Math.sin(progress * Math.PI) * height * .16 + Math.sin(progress * Math.PI * 4.8 + spark.phase) * height * .033 - 4 - Math.sin(time * .0007 + spark.phase) * 5;
    const alpha = Math.sin(progress * Math.PI) * (.34 + Math.sin(time * .001 + spark.phase) * .16);
    motionPoint(memoryMotionContext, x, y, spark.size, spark.violet ? "#c28fff" : "#a7c5ff", Math.max(.08, alpha));
  });
  memoryMotionContext.restore();
}

function stopMotion(clear = false) {
  if (motionFrame) cancelAnimationFrame(motionFrame);
  motionFrame = 0;
  if (clear) {
    heroMotionContext.clearRect(0, 0, heroMotionCanvas.width, heroMotionCanvas.height);
    memoryMotionContext.clearRect(0, 0, memoryMotionCanvas.width, memoryMotionCanvas.height);
  }
}

function motionLoop(time) {
  motionFrame = 0;
  if (document.hidden || manualMotionPaused || (reducedMotionQuery.matches && !motionPreferenceOverride) || (!motionVisible.hero && !motionVisible.memory)) return;
  if (time - lastMotionPaint >= 33) {
    if (motionVisible.hero) drawHeroMotion(time);
    if (motionVisible.memory) drawMemoryMotion(time);
    lastMotionPaint = time;
  }
  motionFrame = requestAnimationFrame(motionLoop);
}

function startMotion() {
  if (!motionFrame && !document.hidden && !manualMotionPaused && (!reducedMotionQuery.matches || motionPreferenceOverride) && (motionVisible.hero || motionVisible.memory)) {
    motionFrame = requestAnimationFrame(motionLoop);
  }
}

